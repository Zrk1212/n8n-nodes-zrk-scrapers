"""Generate nodes/ZrkScrapers/properties.ts from ../scrapers-mcp/src/catalog.json. Run after editing the catalog."""
import json, re
cat = json.load(open('../scrapers-mcp/src/catalog.json'))

def title(name):
    s = re.sub(r'([a-z])([A-Z])', r'\1 \2', name)
    s = s.replace('Url', 'URL').replace('Urls', 'URLs').replace('Sic', 'SIC').replace('Ai ', 'AI ')
    return ' '.join(w if w.isupper() else w[0].upper()+w[1:] for w in s.split())

def desc(p):
    d = p['description'].rstrip('.')
    if p['type'] == 'boolean':
        d = 'Whether to ' + d[0].lower() + d[1:] if not d.lower().startswith('whether') else d
    return d

out = []
opts = [{'name': a['title'], 'value': a['tool'], 'description': a['description'].split('. ')[0], 'action': a['title']} for a in cat['actors']]
opts.sort(key=lambda o: o['name'])
out.append({'displayName': 'Scraper', 'name': 'scraper', 'type': 'options', 'noDataExpression': True,
            'options': opts, 'default': cat['actors'][0]['tool']})
for a in cat['actors']:
    show = {'show': {'scraper': [a['tool']]}}
    for p in a['params']:
        t = p['type']
        prop = {'displayName': title(p['name']), 'name': p['name'], 'displayOptions': show, 'description': desc(p)}
        if p.get('required'): prop['required'] = True
        if t == 'string[]':
            prop.update(type='string', default=', '.join(p.get('example', [])) if p.get('required') else '',
                        placeholder=', '.join(p.get('example', [])) or None,
                        hint='Comma-separated list')
        elif t == 'integer':
            prop.update(type='number', default=0, typeOptions={'minValue': 0})
        elif t == 'boolean':
            prop.update(type='boolean', default=False)
        elif t == 'enum':
            prop.update(type='options', default=p['values'][0],
                        options=[{'name': title(v), 'value': v} for v in p['values']])
        else:
            prop.update(type='string', default='')
        out.append({k: v for k, v in prop.items() if v is not None})
common = [
  {'displayName': 'Max Items', 'name': 'maxItems', 'type': 'number', 'default': 50, 'typeOptions': {'minValue': 1},
   'description': 'Max number of results to return'},
  {'displayName': 'Options', 'name': 'options', 'type': 'collection', 'placeholder': 'Add Option', 'default': {}, 'options': [
    {'displayName': 'Extra Input (JSON)', 'name': 'extraInput', 'type': 'json', 'default': '{}',
     'description': 'Any other actor input fields, merged into the input as-is. See the actor input schema on apify.com.'},
    {'displayName': 'Max Charge (USD)', 'name': 'maxChargeUsd', 'type': 'number', 'default': 1, 'typeOptions': {'minValue': 0.01, 'numberPrecision': 2},
     'description': 'Hard spending cap for this run. Apify stops charging when it is reached.'},
    {'displayName': 'Wait Timeout (Seconds)', 'name': 'waitSecs', 'type': 'number', 'default': 300, 'typeOptions': {'minValue': 10},
     'description': 'How long to wait for the run to finish before failing'},
  ]},
]
out += common
meta = {a['tool']: {'actor': a['actor'], 'limitParam': a.get('limitParam'),
        'listParams': [p['name'] for p in a['params'] if p['type'] == 'string[]'],
        'numberParams': [p['name'] for p in a['params'] if p['type'] == 'integer'],
        'boolParams': [p['name'] for p in a['params'] if p['type'] == 'boolean']} for a in cat['actors']}
ts = "// Generated by gen-properties.py from the scrapers-mcp catalog. Do not edit by hand.\n"
ts += "import type { INodeProperties } from 'n8n-workflow';\n\n"
ts += "export const properties: INodeProperties[] = " + json.dumps(out, indent='\t', ensure_ascii=False) + ";\n\n"
ts += "export interface ScraperMeta {\n\tactor: string;\n\tlimitParam: string | null;\n\tlistParams: string[];\n\tnumberParams: string[];\n\tboolParams: string[];\n}\n\n"
ts += "export const scrapers: Record<string, ScraperMeta> = " + json.dumps(meta, indent='\t') + ";\n"
open('nodes/ZrkScrapers/properties.ts', 'w').write(ts)
print(len(out), 'properties')
